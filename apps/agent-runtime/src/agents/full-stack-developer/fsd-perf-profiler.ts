interface V8ProfileNode {
    id:        number;
    callFrame: {
        functionName: string;
        scriptId:     string;
        url:          string;
        lineNumber:   number;
        columnNumber: number;
    };
    hitCount:  number;
    children?: number[];
}

interface V8Profile {
    nodes:       V8ProfileNode[];
    startTime:   number;
    endTime:     number;
    samples?:    number[];
    timeDeltas?: number[];
}

interface RawProfileOutput {
    url:        string;
    durationMs: number;
    profile:    V8Profile | null;
    error?:     string;
    capturedAt?: string;
}

// Functions whose names indicate browser/engine idle time — excluded from hot list
const IDLE_FRAMES = new Set(['(idle)', '(program)', '(garbage collector)', 'v8::internal']);

/**
 * Parses the JSON written to stdout by the profiling script into a
 * structured CpuProfileReport ranked by self-time. Pure function.
 */
export function parseCpuProfile(rawOutput: string, fallbackUrl = ''): CpuProfileReport {
    let data: RawProfileOutput = { url: fallbackUrl, durationMs: 0, profile: null };

    try {
        const start = rawOutput.indexOf('{');
        const end   = rawOutput.lastIndexOf('}');
        if (start !== -1 && end !== -1) {
            data = JSON.parse(rawOutput.slice(start, end + 1)) as RawProfileOutput;
        }
    } catch {
        // fall through — use empty data
    }

    const emptyReport = (msg: string): CpuProfileReport => ({
        targetUrl:    data.url || fallbackUrl,
        totalSamples: 0,
        durationMs:   data.durationMs,
        hotFunctions: [],
        score:        100,
        summary:      msg,
    });

    if (!data.profile) {
        const msg = data.error
            ? `Profiling error: ${data.error}`
            : 'No profile data — ensure Playwright is installed (npm install playwright).';
        return emptyReport(msg);
    }

    const nodes        = data.profile.nodes ?? [];
    const sampleCount  = (data.profile.samples ?? []).length;
    // Fall back to sum of hitCounts when samples array is absent
    const totalSamples = sampleCount > 0
        ? sampleCount
        : nodes.reduce((s, n) => s + (n.hitCount ?? 0), 0);

    if (totalSamples === 0) return emptyReport('Profile captured 0 samples — page may be idle.');

    // Rank non-idle nodes by hitCount descending
    const ranked = nodes
        .filter((n) => (n.hitCount ?? 0) > 0 && !isIdleFrame(n.callFrame.functionName))
        .sort((a, b) => (b.hitCount ?? 0) - (a.hitCount ?? 0))
        .slice(0, 15);

    const hotFunctions: HotFunction[] = ranked.map((node, i) => ({
        rank:         i + 1,
        functionName: node.callFrame.functionName || '(anonymous)',
        url:          node.callFrame.url,
        lineNumber:   node.callFrame.lineNumber,
        hitCount:     node.hitCount ?? 0,
        selfPercent:  parseFloat(((node.hitCount / totalSamples) * 100).toFixed(1)),
    }));

    const { score, summary } = summarisePerfProfile(hotFunctions, totalSamples, data.url);
    return { targetUrl: data.url, totalSamples, durationMs: data.durationMs, hotFunctions, score, summary };
}

function isIdleFrame(name: string): boolean {
    if (!name) return false;
    for (const idle of IDLE_FRAMES) {
        if (name.startsWith(idle)) return true;
    }
    return false;
}

