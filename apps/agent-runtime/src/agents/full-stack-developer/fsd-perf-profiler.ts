// ============================================================================
// FSD PERF PROFILER
// Sprint 16 — Full-Stack Developer Role
//
// Live CPU hot-path detection via Chrome DevTools Protocol (CDP).
// Playwright attaches a CDP session, enables the V8 Profiler domain, records
// samples for N milliseconds, then returns a ranked list of hot functions —
// exactly what a developer sees in the Chrome DevTools Performance tab.
//
// buildPlaywrightProfilingScript → self-contained CJS script (write + run via Node)
// parseCpuProfile               → structures V8 .cpuprofile JSON → CpuProfileReport
// buildPerfOptimizationPrompt   → LLM prompt: analyse hot functions + suggest fixes
// applyPerfSuggestions          → merges LLM hints back into HotFunction[]
// summarisePerfProfile          → score (0–100) + one-line summary
// ============================================================================

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export interface HotFunction {
    rank:         number;
    functionName: string;    // "(anonymous)" if unnamed
    url:          string;    // source file URL
    lineNumber:   number;
    hitCount:     number;    // raw V8 sample count
    selfPercent:  number;    // % of total samples on this frame (1 d.p.)
    suggestion?:  string;    // filled by LLM pass
}

export interface CpuProfileReport {
    targetUrl:    string;
    totalSamples: number;
    durationMs:   number;
    hotFunctions: HotFunction[];   // top ≤15 by selfPercent, idle excluded
    score:        number;          // 0–100 (100 = well-distributed, no hotspot)
    summary:      string;
}

// ---------------------------------------------------------------------------
// buildPlaywrightProfilingScript
// ---------------------------------------------------------------------------

/**
 * Returns a self-contained CommonJS script that:
 *   1. Launches headless Chromium via Playwright
 *   2. Opens a CDP session and enables the V8 Profiler domain
 *   3. Navigates to the target URL and waits for the page to load
 *   4. Records CPU samples for `durationMs` milliseconds
 *   5. Writes the raw V8 profile JSON to stdout
 *
 * The caller writes this string to disk (__fsd_perf_profile.cjs)
 * and runs it via runCommand(['node', path]).
 * Pure function — no side-effects.
 */
export function buildPlaywrightProfilingScript(url: string, durationMs = 5_000): string {
    return `
// Auto-generated by fsd-perf-profiler — safe to delete after run
'use strict';
const { chromium } = require('playwright');

const TARGET_URL  = ${JSON.stringify(url)};
const DURATION_MS = ${durationMs};

(async () => {
    let browser;
    try {
        browser = await chromium.launch({ headless: true });
        const context = await browser.newContext({ ignoreHTTPSErrors: true });
        const page    = await context.newPage();

        // ── Navigate first so the page's JS is loaded ───────────────────────
        try {
            await page.goto(TARGET_URL, { waitUntil: 'load', timeout: 30000 });
        } catch (navErr) {
            console.log(JSON.stringify({
                url: TARGET_URL, durationMs: DURATION_MS,
                error: 'Navigation failed: ' + navErr.message, profile: null,
            }));
            return;
        }

        // ── Attach CDP session ───────────────────────────────────────────────
        const client = await context.newCDPSession(page);
        await client.send('Profiler.enable');
        // 100 μs sampling interval (default is 1000 μs — finer granularity)
        await client.send('Profiler.setSamplingInterval', { interval: 100 });

        // ── Profile for the requested duration ───────────────────────────────
        await client.send('Profiler.start');
        await new Promise((resolve) => setTimeout(resolve, DURATION_MS));
        const { profile } = await client.send('Profiler.stop');

        await client.detach();

        console.log(JSON.stringify({
            url:        TARGET_URL,
            durationMs: DURATION_MS,
            profile,
            capturedAt: new Date().toISOString(),
        }));

    } catch (err) {
        console.log(JSON.stringify({
            url:        TARGET_URL,
            durationMs: DURATION_MS,
            error:      err.message,
            profile:    null,
        }));
    } finally {
        try { if (browser) await browser.close(); } catch (_) {}
    }
})();
`.trim();
}

