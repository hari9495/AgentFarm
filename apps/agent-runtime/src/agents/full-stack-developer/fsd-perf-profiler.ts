/**
 * Crafts the LLM prompt that analyses the hot functions and asks for
 * specific optimisation suggestions for the worst offenders. Pure function.
 */
export function buildPerfOptimizationPrompt(
    report:     CpuProfileReport,
    sourceCode?: string,
): string {
    const hotList = report.hotFunctions.slice(0, 10).map((fn) =>
        `${fn.rank}. ${fn.functionName} — ${fn.selfPercent}% of CPU (${fn.hitCount} samples)`
        + (fn.url ? `\n   Source: ${fn.url}${fn.lineNumber ? `:${fn.lineNumber}` : ''}` : ''),
    ).join('\n');

    const codeBlock = sourceCode
        ? `\nRelevant source code:\n\`\`\`\n${sourceCode.slice(0, 3000)}\n\`\`\``
        : '';

    return [
        `You are a senior performance engineer analysing a V8 CPU profile.`,
        `App URL: ${report.targetUrl}`,
        `Profile duration: ${report.durationMs}ms, ${report.totalSamples} total samples.`,
        ``,
        `Top CPU hot functions (by self-time %):`,
        hotList,
        codeBlock,
        ``,
        `For each numbered function, provide a concrete optimisation.`,
        `Focus on: memoisation, algorithm complexity, unnecessary re-renders,`,
        `expensive DOM operations, synchronous blocking, or missing lazy-loading.`,
        ``,
        `Return a JSON array where each object has:`,
        `  id          — matches the function number (1, 2, 3, …)`,
        `  cause       — why this function is a hotspot (one sentence)`,
        `  suggestion  — specific code change or architectural fix`,
        `  impact      — expected improvement: high | medium | low`,
        ``,
        `No markdown fences, no prose — only the JSON array.`,
    ].filter(Boolean).join('\n');
}

