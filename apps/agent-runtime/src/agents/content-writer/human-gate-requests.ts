/**
 * human-gate-requests.ts
 *
 * Defines the structured human validation gates for the Content Writer agent.
 *
 * These are capabilities the agent cannot perform autonomously:
 *   - Competitive analysis
 *   - A/B variant generation
 *   - Audience persona buildup
 *   - Style guide enforcement
 *   - Distribution planning
 *   - Legal/compliance review
 *   - Evergreen content maintenance
 *   - AI disclosure metadata
 *
 * When the agent reaches one of these gaps, it calls workspace_cw_request_human_gate.
 * The action routes to the approval queue (always high-risk) so the admin/customer
 * can review the draft context and approve, reject, or provide guidance.
 *
 * Security note: all summary/label strings are derived from FIXED template text —
 * never from raw user-supplied draft body content — to prevent prompt injection
 * in the approval queue.
 */

