/**
 * Crafts an LLM prompt that analyses the captured browser errors and asks for
 * a concrete fix for each one. Pure function.
 */
export function buildDebugAnalysisPrompt(report: BrowserDebugReport, sourceCode?: string): string {
    const errorLines = report.errors.map((e, i) =>
        `${i + 1}. [${e.source}/${e.severity}] ${e.message}`
        + (e.stackTrace ? `\n   Stack: ${e.stackTrace.slice(0, 300)}` : ''),
    ).join('\n');

    const netLines = report.networkFailures.map(
        (nf) => `- ${nf.method} ${nf.url} → ${nf.status} ${nf.statusText}`,
    ).join('\n');

    const codeBlock = sourceCode
        ? `\nRelevant source code:\n\`\`\`\n${sourceCode.slice(0, 3000)}\n\`\`\``
        : '';

    return [
        `You are a senior full-stack developer debugging a live web application.`,
        `The app at "${report.targetUrl}" produced the following runtime errors:`,
        ``,
        errorLines || '(no console errors)',
        netLines ? `\nFailed network requests:\n${netLines}` : '',
        codeBlock,
        ``,
        `For each numbered error, provide a concrete fix.`,
        ``,
        `Return a JSON array where each object has:`,
        `  id    — the error number (1, 2, 3, …) matching the list above`,
        `  cause — root cause in one sentence`,
        `  fix   — specific code change, config change, or dependency fix`,
        ``,
        `No markdown fences, no prose — only the JSON array.`,
    ].filter(Boolean).join('\n');
}

// ---------------------------------------------------------------------------
// applyDebugSuggestions
// ---------------------------------------------------------------------------

/**
 * Merges LLM fix suggestions back into the BrowserError array by index.
 * Pure function.
 */
export function applyDebugSuggestions(raw: string, errors: BrowserError[]): BrowserError[] {
    const cleaned = raw.replace(/^```[a-z]*\n?/im, '').replace(/```\s*$/im, '').trim();
    const start   = cleaned.indexOf('[');
    const end     = cleaned.lastIndexOf(']');
    if (start === -1 || end === -1) return errors;

    try {
        const suggestions = JSON.parse(cleaned.slice(start, end + 1)) as Array<{
            id?:    number;
            cause?: string;
            fix?:   string;
        }>;

        return errors.map((err, idx) => {
            const s = suggestions.find((item) => item.id === idx + 1);
            if (!s) return err;
            const parts = [s.cause, s.fix ? `Fix: ${s.fix}` : ''].filter(Boolean);
            return { ...err, suggestion: parts.join(' — ') || err.suggestion };
        });
    } catch {
        return errors;
    }
}

// ---------------------------------------------------------------------------
// summariseBrowserReport
// ---------------------------------------------------------------------------

/**
 * Computes a 0–100 quality score and a one-line summary. Pure function.
 */
export function summariseBrowserReport(
    errors:          BrowserError[],
    networkFailures: NetworkFailure[],
): { score: number; summary: string } {
    const errorCount   = errors.filter((e) => e.severity === 'error').length;
    const warningCount = errors.filter((e) => e.severity === 'warning').length;
    const serverErrors = networkFailures.filter((nf) => nf.status >= 500).length;

    const score = Math.max(0, 100 - errorCount * 15 - warningCount * 5 - serverErrors * 10);

    if (errors.length === 0 && networkFailures.length === 0) {
        return { score: 100, summary: 'No runtime errors detected.' };
    }

    const worst = errors.find((e) => e.severity === 'error') ?? errors[0]!;
    return {
        score,
        summary: `Runtime debug: score ${score}/100 — ${errorCount} error(s), ${warningCount} warning(s), ${networkFailures.length} network failure(s). Worst: ${worst.message.slice(0, 80)}`,
    };
}
