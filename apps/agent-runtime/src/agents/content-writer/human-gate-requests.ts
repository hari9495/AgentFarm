// Types
// ---------------------------------------------------------------------------

/**
 * The set of human validation gates the Content Writer agent can request.
 *
 * Mandatory blockers (legal/compliance risk):
 *   - legal_review   — must not publish without legal sign-off
 *   - ai_disclosure  — AI-generated content disclosure is legally required in many jurisdictions
 *
 * Advisory gates (strategy/quality gaps):
 *   - competitive_analysis, ab_variant, audience_persona, style_guide,
 *     distribution_plan, evergreen_update
 */
export type ContentWriterGateType =
    | 'competitive_analysis'
    | 'ab_variant'
    | 'audience_persona'
    | 'style_guide'
    | 'distribution_plan'
    | 'legal_review'
    | 'evergreen_update'
    | 'ai_disclosure';

