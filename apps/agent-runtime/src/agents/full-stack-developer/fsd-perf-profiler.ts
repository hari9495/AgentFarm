// applyPerfSuggestions
// ---------------------------------------------------------------------------

/**
 * Merges LLM optimisation suggestions back into the HotFunction array.
 * Pure function.
 */
export function applyPerfSuggestions(raw: string, hotFunctions: HotFunction[]): HotFunction[] {
    const cleaned = raw.replace(/^```[a-z]*\n?/im, '').replace(/```\s*$/im, '').trim();
    const start   = cleaned.indexOf('[');
    const end     = cleaned.lastIndexOf(']');
    if (start === -1 || end === -1) return hotFunctions;

    try {
        const suggestions = JSON.parse(cleaned.slice(start, end + 1)) as Array<{
            id?:         number;
            cause?:      string;
            suggestion?: string;
            impact?:     string;
        }>;

        return hotFunctions.map((fn) => {
            const s = suggestions.find((item) => item.id === fn.rank);
            if (!s) return fn;
            const parts = [
                s.cause,
                s.suggestion ? `Fix: ${s.suggestion}` : '',
                s.impact     ? `(${s.impact} impact)`  : '',
            ].filter(Boolean);
            return { ...fn, suggestion: parts.join(' — ') };
        });
    } catch {
        return hotFunctions;
    }
}

// ---------------------------------------------------------------------------
// summarisePerfProfile
// ---------------------------------------------------------------------------

/**
 * Computes a 0–100 score and one-line summary from the hot function list.
 *
 * Scoring model:
 *   - Ideal: no single function over 5% self-time → score ~100
 *   - Each percent of the top function costs ~1.5 score points
 *   - Second function contributes half as much
 * Pure function.
 */
export function summarisePerfProfile(
    hotFunctions: HotFunction[],
    totalSamples: number,
    targetUrl:    string,
): { score: number; summary: string } {
    if (hotFunctions.length === 0 || totalSamples === 0) {
        return { score: 100, summary: 'No hot functions detected — app appears idle or is well-optimised.' };
    }

    const top    = hotFunctions[0]!;
    const second = hotFunctions[1];

    const score = Math.max(
        0,
        Math.round(100 - top.selfPercent * 1.5 - (second?.selfPercent ?? 0) * 0.5),
    );

    const topLabel = top.functionName === '(anonymous)'
        ? `anonymous fn at ${top.url ? top.url.split('/').pop() ?? top.url : 'unknown'}:${top.lineNumber}`
        : top.functionName;

    return {
        score,
        summary: `CPU profile (${totalSamples} samples): score ${score}/100. Hot path: "${topLabel}" at ${top.selfPercent}% self-time. ${hotFunctions.length} functions profiled.`,
    };
}
